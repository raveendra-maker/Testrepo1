package day;

public class Substring {
	public static void main(String[] args) {
		
		String str="raveendraaa";
		System.out.println(str.substring(1));//starts giving output from 1st index
		
		String str1="chintapalli";
		System.out.println(str1.substring(4, 9)); //start giving the element from index 4 to 8 and exclude index 9

		
		
	}

}
